package JavaOperators;

public class UnaryOperators {

	public static void main(String[] args) {
	int x = 10;
	int y = 20;
	
	int result = +x;
	System.out.println("+x =" + result);
	
	int result = -y;
	System.out.println("-y =" + result);
	
	int result = +x;
	System.out.println("+x =" + result);
	
	int result = ++x;
	System.out.println("++x =" + result);
	
	
	int result = --y;
	System.out.println("--y =" + result);
	boolean ok = false;
	
	System.out.println(ok);
	System.out.println(!ok);


	}

}
