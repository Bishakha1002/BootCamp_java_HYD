package DecisionMakingStatements;

public class Switch {

	public static void main(String[] args) {
		int num = 2;
		
		
		switch(num) {
		case 0 :
			System.out.println("number is 0:coforge");
			break;
		case 1:
			System.out.println("number is 1:Bishu");
			break;
		case 2:
			System.out.println("number is 2: Bishakha");
			break;
		case 3:
			System.out.println("number is 3: Banglore");
			break;
		default:
			System.out.println(num);
		
		}

	}

}
