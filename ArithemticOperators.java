package JavaOperators;

public class ArithemticOperators {

	public static void main(String[] args) {
		int a = 24;
		int b = 45;
		
		int result = 0;
		
		result = a+b;
		System.out.println("a + b = "+result);
		
		result = a-b;
		System.out.println("a - b = "+result);
		
		result= a*b;
		System.out.println("a * b = "+result);
		
		result= a%b;
		System.out.println("a % b = "+result);
		
		

	}

}
