package JavaOperators;

public class RelationalOperators {

	public static void main(String[] args) {
		int x = 24;
		int y = 28;
		
		boolean result = x==y;
		System.out.println("x==y?" +result);
		
		result = x != y;
		System.out.println("x!=y?" +result);
		
		result = x >= y;
		System.out.println("x>=y?" +result);
		
		result = x > y;
		System.out.println("x>y?" +result);
		
		
		
		
		

	}

}
